  // ---------- tiny DOM helpers
  function h(tag, attrs) {
    var el = document.createElement(tag);
    if (attrs) for (var k in attrs) {
      if (attrs[k] == null || attrs[k] === false) continue;
      if (k === 'text') el.textContent = attrs[k];
      else if (k === 'on') for (var ev in attrs.on) el.addEventListener(ev, attrs.on[ev]);
      else if (k === 'cls') el.className = attrs[k];
      else el.setAttribute(k, attrs[k] === true ? '' : attrs[k]);
    }
    for (var i = 2; i < arguments.length; i++) {
      var c = arguments[i];
      if (c == null || c === false) continue;
      el.appendChild(typeof c === 'string' ? document.createTextNode(c) : c);
    }
    return el;
  }
  function s(tag, attrs) {
    var el = document.createElementNS(SVGNS, tag);
    if (attrs) for (var k in attrs) if (attrs[k] != null) el.setAttribute(k, attrs[k]);
    return el;
  }
  function $(id) { return document.getElementById(id); }
  function clear(el) { while (el.firstChild) el.removeChild(el.firstChild); return el; }
  function tag(p) { return h('span', { cls: 'tag ' + p, text: p }); }
  function plural(n, w) { return n + ' ' + w + (n === 1 ? '' : 's'); }

  function srcLink(path, line) {
    var label = path + (line ? ':' + line : '');
    var href = null;
    if (CFG.editorRoot) href = 'vscode://file/' + CFG.editorRoot.replace(/\/$/, '') + '/' + path + (line ? ':' + line : '');
    else if (CFG.sourceBase != null) href = CFG.sourceBase + path.split('/').map(encodeURIComponent).join('/');
    var wrap = h('span', null);
    if (href) wrap.appendChild(h('a', { href: href, text: label, title: 'Open source file' }));
    else wrap.appendChild(h('span', { cls: 'loc', text: label }));
    wrap.appendChild(document.createTextNode(' '));
    wrap.appendChild(h('button', { type: 'button', text: 'copy', 'aria-label': 'Copy location ' + label, on: { click: function (e) { copy(label, e.currentTarget); } } }));
    return wrap;
  }
  function copy(text, btn) {
    var done = function () { if (btn) { var t = btn.textContent; btn.textContent = 'copied'; setTimeout(function () { btn.textContent = t; }, 1200); } };
    if (navigator.clipboard && window.isSecureContext) navigator.clipboard.writeText(text).then(done, fallback);
    else fallback();
    function fallback() {
      var ta = h('textarea', { 'aria-hidden': 'true', style: 'position:fixed;left:-9999px' });
      ta.value = text; document.body.appendChild(ta); ta.select();
      try { document.execCommand('copy'); done(); } catch (e) { /* ignore */ }
      document.body.removeChild(ta);
    }
  }

