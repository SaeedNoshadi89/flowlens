  // ---------- map
  function renderMap(refit) {
    view = C.computeView(G, st);
    lay = C.layout(view, CFG.maxNodes || 700);
    var svg = clear($('svg'));
    var defs = s('defs');
    var f = s('filter', { id: 'glow', x: '-30%', y: '-30%', width: '160%', height: '160%' });
    f.appendChild(s('feGaussianBlur', { stdDeviation: '3', result: 'b' }));
    var m = s('feMerge'); m.appendChild(s('feMergeNode', { in: 'b' })); m.appendChild(s('feMergeNode', { in: 'SourceGraphic' }));
    f.appendChild(m); defs.appendChild(f);
    C.RELATIONS.forEach(function (r) {
      var mk = s('marker', { id: 'arrow-' + r, viewBox: '0 0 10 10', refX: '9', refY: '5', markerWidth: '7', markerHeight: '7', orient: 'auto-start-reverse' });
      mk.appendChild(s('path', { d: 'M0,0 L10,5 L0,10 z', fill: 'var(--r-' + r + ')' }));
      defs.appendChild(mk);
    });
    svg.appendChild(defs);
    var g = s('g', { id: 'world' });
    lay.lanes.forEach(function (l) {
      g.appendChild(s('rect', { class: 'lane-bg', x: l.x - 14, y: 16, width: C.NODE_W + 28, height: lay.height - 10, rx: 14 }));
      var t = s('text', { class: 'lane-h', x: l.x, y: 40, fill: l.color }); t.textContent = l.title + ' · ' + l.count; g.appendChild(t);
    });
    var marks = C.replayMarks(G, st.scenario ? IX.scenarios[st.scenario] : null, st.step);
    var eg = s('g', { id: 'edges' });
    view.edges.forEach(function (e) {
      var a = lay.pos[e.from], b = lay.pos[e.to];
      if (!a || !b) return;
      var d = C.edgePath(a, b);
      var cls = 'edge ' + e.provenance;
      var isActive = marks.active && e.members.indexOf(marks.active.edge) >= 0;
      var isSeen = e.members.some(function (id) { return marks.seenEdges[id]; });
      if (isActive) cls += ' active'; else if (isSeen) cls += ' seen';
      if (st.selectedEdge && e.members.indexOf(st.selectedEdge) >= 0) cls += ' sel';
      if (st.scenario && st.step >= 0 && !isSeen) cls += ' dim';
      var p = s('path', { class: cls, d: d, stroke: 'var(--r-' + e.relation + ')', 'marker-end': 'url(#arrow-' + e.relation + ')', 'data-edge': e.members[0] });
      eg.appendChild(p);
      var hit = s('path', { class: 'edge-hit', d: d });
      var tt = s('title'); tt.textContent = edgeSummary(e); hit.appendChild(tt);
      hit.addEventListener('click', function (ev) { ev.stopPropagation(); selectEdge(e.members[0], e); });
      eg.appendChild(hit);
      if (e.count > 1) {
        var mx = (a.x + a.w + b.x) / 2, my = (a.y + b.y) / 2 + a.h / 2 - 4;
        var ct = s('text', { class: 'ecount', x: mx, y: my, 'text-anchor': 'middle' }); ct.textContent = '×' + e.count; eg.appendChild(ct);
      }
      if (isActive && !reduced) {
        var dot = s('circle', { class: 'pulse', r: '5' });
        var am = s('animateMotion', { dur: (C.stepDelay(st.speed) / 1000 * 0.8) + 's', repeatCount: 'indefinite', path: d });
        dot.appendChild(am); eg.appendChild(dot);
      }
    });
    g.appendChild(eg);
    var matches = {};
    if (st.query) C.search(G, st.query, 500).forEach(function (n) { matches[n.id] = true; });
    var ng = s('g', { id: 'nodes' });
    view.nodes.forEach(function (n) {
      var p = lay.pos[n.id];
      if (!p) return;
      var cls = 'node';
      if (marks.active && (marks.active.to === n.id)) cls += ' active';
      else if (marks.seenNodes[n.id]) cls += ' seen';
      if (st.scenario && st.step >= 0 && !marks.seenNodes[n.id]) cls += ' dim';
      if (st.selected === n.id) cls += ' sel';
      if (st.query && matches[n.id]) cls += ' match';
      else if (st.query) cls += ' dim';
      var grp = s('g', { class: cls, transform: 'translate(' + p.x + ',' + p.y + ')', tabindex: '0', role: 'button', 'data-node': n.id, 'aria-label': n.kind + ' ' + n.label + (n.path ? ' in ' + n.path : ''), style: '--kc:' + C.colorOf(n) });
      grp.appendChild(s('rect', { class: 'box', width: p.w, height: p.h, rx: 9 }));
      grp.appendChild(s('rect', { class: 'bar', width: 4, height: p.h - 12, x: 6, y: 6, rx: 2 }));
      grp.appendChild(s('rect', { class: 'frame', x: -4, y: -4, width: p.w + 8, height: p.h + 8, rx: 12 }));
      var lbl = s('text', { class: 'lbl', x: 18, y: 20 }); lbl.textContent = fit(n.label, 23); grp.appendChild(lbl);
      var sub = s('text', { class: 'sub', x: 18, y: 36 }); sub.textContent = fit(subText(n), 27); grp.appendChild(sub);
      var tt = s('title'); tt.textContent = n.kind + ': ' + n.label + (n.path ? '\n' + n.path + (n.line ? ':' + n.line : '') : ''); grp.appendChild(tt);
      grp.addEventListener('click', function (ev) { ev.stopPropagation(); selectNode(n.id); });
      grp.addEventListener('keydown', function (ev) { if (ev.key === 'Enter' || ev.key === ' ') { ev.preventDefault(); selectNode(n.id); } });
      ng.appendChild(grp);
    });
    g.appendChild(ng);
    svg.appendChild(g);
    var empty = $('empty');
    if (!view.nodes.length) { empty.hidden = false; empty.textContent = 'Nothing matches the current filters. Turn relationships or features back on.'; }
    else empty.hidden = true;
    $('mapnote').textContent = (lay.truncated ? 'Showing ' + lay.shown + ' of ' + lay.total + ' nodes (most connected). Narrow the features filter to see the rest. · ' : '') +
      (st.scenario ? 'Scenario view' : st.level === 'modules' ? 'Overview · modules' : 'Overview · functions') + ' · drag to pan, scroll or +/− to zoom, 0 to fit';
    if (refit || !vb) fitView(); else applyViewBox();
    if (marks.active) { if (st.follow) followStep(marks.active); else ensureVisible(marks.active.to); }
  }
  function fit(t, n) { return t.length > n ? t.slice(0, n - 1) + '…' : t; }
  function subText(n) {
    if (n.kind === 'function' || n.kind === 'request') return (n.sub || '') + (n.line ? ':' + n.line : '');
    if (n.kind === 'module') return n.sub || '(root)';
    return n.sub || n.kind;
  }
  function edgeSummary(e) {
    var a = IX.nodes[e.from], b = IX.nodes[e.to];
    return (a ? a.label : e.from) + ' → ' + (b ? b.label : e.to) + ' · ' + e.relation + ' · ' + e.provenance + (e.count > 1 ? ' · ' + e.count + ' edges' : '');
  }

  // ---------- pan and zoom (viewBox)
  function fitView(whole) {
    if (!lay) return;
    var svg = $('svg');
    var cw = svg.clientWidth || 1000, ch = svg.clientHeight || 600;
    var lw = Math.max(lay.width, 300), lh = Math.max(lay.height, 200);
    var scale = Math.min(cw / lw, ch / lh);
    // Keep labels readable: when the whole map would be tiny, fit the width and let the user pan down.
    if (!whole && scale < 0.75) scale = Math.min(cw / lw, 1);
    scale = Math.max(whole ? 0.2 : 0.62, Math.min(scale, 1.35));
    var w = cw / scale, hgt = ch / scale;
    vb = { x: Math.min(0, (lw - w) / 2), y: 0, w: w, h: hgt };
    if (lh < hgt) vb.y = Math.min(0, (lh - hgt) / 2);
    applyViewBox();
  }
  function applyViewBox() { $('svg').setAttribute('viewBox', [vb.x, vb.y, vb.w, vb.h].join(' ')); }
  function zoom(factor, cx, cy) {
    var nw = Math.min(Math.max(vb.w * factor, 200), 20000), nh = vb.h * (nw / vb.w);
    if (cx == null) { cx = vb.x + vb.w / 2; cy = vb.y + vb.h / 2; }
    vb.x = cx - (cx - vb.x) * (nw / vb.w); vb.y = cy - (cy - vb.y) * (nh / vb.h); vb.w = nw; vb.h = nh;
    applyViewBox();
  }
  /** Camera that keeps the active step readable: both ends in view when they fit, else the target. */
  function followStep(step) {
    var a = lay.pos[step.from], b = lay.pos[step.to];
    if (!b || !vb) return;
    var svg = $('svg');
    var cw = svg.clientWidth || 1000, ch = svg.clientHeight || 600;
    var scale = Math.max(cw / vb.w, 0.9);
    var w = cw / scale, hgt = ch / scale;
    var x0 = a ? Math.min(a.x, b.x) : b.x, x1 = a ? Math.max(a.x + a.w, b.x + b.w) : b.x + b.w;
    var y0 = a ? Math.min(a.y, b.y) : b.y, y1 = a ? Math.max(a.y + a.h, b.y + b.h) : b.y + b.h;
    if (x1 - x0 > w - 60) { x0 = b.x; x1 = b.x + b.w; }
    if (y1 - y0 > hgt - 60) { y0 = b.y; y1 = b.y + b.h; }
    vb = { x: (x0 + x1) / 2 - w / 2, y: Math.max(-20, (y0 + y1) / 2 - hgt / 2), w: w, h: hgt };
    applyViewBox();
  }
  function ensureVisible(id) {
    var p = lay && lay.pos[id];
    if (!p || !vb) return;
    var margin = 40;
    if (p.x >= vb.x + margin && p.x + p.w <= vb.x + vb.w - margin && p.y >= vb.y + margin && p.y + p.h <= vb.y + vb.h - margin) return;
    vb.x = p.x + p.w / 2 - vb.w / 2; vb.y = p.y + p.h / 2 - vb.h / 2;
    applyViewBox();
  }
  function bindPanZoom() {
    var svg = $('svg');
    var drag = null;
    svg.addEventListener('wheel', function (e) {
      e.preventDefault();
      var r = svg.getBoundingClientRect();
      var cx = vb.x + (e.clientX - r.left) / r.width * vb.w, cy = vb.y + (e.clientY - r.top) / r.height * vb.h;
      zoom(e.deltaY > 0 ? 1.12 : 1 / 1.12, cx, cy);
    }, { passive: false });
    svg.addEventListener('pointerdown', function (e) {
      if (e.target.closest && (e.target.closest('.node') || e.target.classList.contains('edge-hit'))) return;
      drag = { x: e.clientX, y: e.clientY, vx: vb.x, vy: vb.y, moved: false };
      svg.setPointerCapture(e.pointerId); svg.classList.add('dragging');
    });
    svg.addEventListener('pointermove', function (e) {
      if (!drag) return;
      var r = svg.getBoundingClientRect();
      var dx = (e.clientX - drag.x) / r.width * vb.w, dy = (e.clientY - drag.y) / r.height * vb.h;
      if (Math.abs(e.clientX - drag.x) + Math.abs(e.clientY - drag.y) > 3) drag.moved = true;
      vb.x = drag.vx - dx; vb.y = drag.vy - dy; applyViewBox();
    });
    var end = function () { if (drag && !drag.moved) { st.selected = null; st.selectedEdge = null; renderDetails(); renderMap(false); syncHash(); } drag = null; svg.classList.remove('dragging'); };
    svg.addEventListener('pointerup', end);
    svg.addEventListener('pointercancel', function () { drag = null; svg.classList.remove('dragging'); });
  }

