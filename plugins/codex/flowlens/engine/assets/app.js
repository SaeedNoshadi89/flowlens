  function go(delta) {
    var sc = st.scenario ? IX.scenarios[st.scenario] : null;
    if (!sc) return;
    st.step = C.moveStep(st, sc, delta);
    var a = sc.steps[st.step];
    st.selectedEdge = a ? a.edge : null;
    st.selected = null;
    renderStep();
  }
  function jump(i) { stop(); st.step = i; var sc = IX.scenarios[st.scenario]; st.selectedEdge = sc.steps[i] ? sc.steps[i].edge : null; st.selected = null; renderStep(); }
  function play() {
    var sc = st.scenario ? IX.scenarios[st.scenario] : null;
    if (!sc) return;
    if (st.step >= sc.steps.length - 1) st.step = -1;
    st.playing = true;
    tick();
  }
  function tick() {
    clearTimeout(timer);
    var sc = st.scenario ? IX.scenarios[st.scenario] : null;
    if (!st.playing || !sc) return;
    go(1);
    if (st.step >= sc.steps.length - 1) { st.playing = false; renderControls(); syncHash(); return; }
    timer = setTimeout(tick, C.stepDelay(st.speed));
  }
  function stop() { st.playing = false; clearTimeout(timer); }
