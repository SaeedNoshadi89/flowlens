  function bindKeys() {
    document.addEventListener('keydown', function (e) {
      var tagName = (e.target && e.target.tagName) || '';
      if (/INPUT|TEXTAREA|SELECT/.test(tagName)) return;
      if (e.key === '/') { e.preventDefault(); $('q').focus(); return; }
      if (e.key === 'ArrowRight') { e.preventDefault(); stop(); go(1); }
      else if (e.key === 'ArrowLeft') { e.preventDefault(); stop(); go(-1); }
      else if (e.key === ' ' && !/BUTTON|A/.test(tagName) && !(e.target.getAttribute && e.target.getAttribute('role') === 'button')) { e.preventDefault(); toggleplay(); }
      else if (e.key === 'Home') { e.preventDefault(); stop(); st.step = -1; renderStep(); }
      else if (e.key === '+' || e.key === '=') zoom(1 / 1.2);
      else if (e.key === '-') zoom(1.2);
      else if (e.key === '0') fitView(true);
      else if (e.key === 'Escape') { st.selected = null; st.selectedEdge = null; renderDetails(); renderMap(false); syncHash(); }
    });
  }
