import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { SELECTABLE_RELATIONS, type SelectableRelation } from '../graph/schema.ts';
import { PRESET_NAMES, type PresetName } from './presets.ts';

export const SETTINGS_DIR = '.flowlens';
export const SETTINGS_FILE = 'config.json';

/** Per-project preferences, saved at <root>/.flowlens/config.json. */
export interface ProjectSettings {
  version: 1;
  /** Presets that produced `include`; "custom" when the user edited the paths. */
  presets: (PresetName | 'custom')[];
  include: string[];
  exclude: string[];
  relations: SelectableRelation[];
  /** Output folder relative to the root. */
  outDir: string;
  /** Optional feature groups: name -> path prefixes. */
  features?: Record<string, string[]>;
  /** Add vscode:// links to evidence (embeds absolute paths in the report). Off by default. */
  editorLinks?: boolean;
}

export function defaultSettings(): ProjectSettings {
  return {
    version: 1,
    presets: ['whole'],
    include: [],
    exclude: [],
    relations: [...SELECTABLE_RELATIONS],
    outDir: SETTINGS_DIR,
  };
}

export function settingsPath(root: string): string {
  return path.join(root, SETTINGS_DIR, SETTINGS_FILE);
}

export function loadSettings(root: string): { settings: ProjectSettings; found: boolean } {
  const p = settingsPath(root);
  if (!existsSync(p)) return { settings: defaultSettings(), found: false };
  const raw = JSON.parse(readFileSync(p, 'utf8')) as Partial<ProjectSettings>;
  return { settings: normalizeSettings(raw), found: true };
}

export function normalizeSettings(raw: Partial<ProjectSettings>): ProjectSettings {
  const d = defaultSettings();
  const relations = Array.isArray(raw.relations)
    ? raw.relations.filter((r): r is SelectableRelation => (SELECTABLE_RELATIONS as readonly string[]).includes(r))
    : d.relations;
  const presets = Array.isArray(raw.presets)
    ? raw.presets.filter((p): p is PresetName | 'custom' => p === 'custom' || (PRESET_NAMES as readonly string[]).includes(p))
    : d.presets;
  const cleanPaths = (xs: unknown): string[] =>
    Array.isArray(xs) ? xs.filter((x): x is string => typeof x === 'string').map(cleanRel).filter((x) => x !== null) as string[] : [];
  const out: ProjectSettings = {
    version: 1,
    presets: presets.length ? presets : d.presets,
    include: cleanPaths(raw.include),
    exclude: Array.isArray(raw.exclude) ? raw.exclude.filter((x): x is string => typeof x === 'string') : [],
    relations: relations.length ? relations : d.relations,
    outDir: typeof raw.outDir === 'string' && cleanRel(raw.outDir) !== null ? cleanRel(raw.outDir)! : d.outDir,
  };
  if (raw.features && typeof raw.features === 'object') out.features = raw.features;
  if (raw.editorLinks === true) out.editorLinks = true;
  return out;
}

/** Normalize a repository-relative path; null if it escapes the root. */
export function cleanRel(p: string): string | null {
  const n = path.posix.normalize(p.replace(/\\/g, '/')).replace(/^(\.\/)+/, '').replace(/\/+$/, '');
  if (n === '.' || n === '') return '';
  if (n.startsWith('../') || n === '..' || n.startsWith('/')) return null;
  return n;
}

export function saveSettings(root: string, settings: ProjectSettings): string {
  const dir = path.join(root, SETTINGS_DIR);
  mkdirSync(dir, { recursive: true });
  ensureOutputIgnore(dir);
  const p = settingsPath(root);
  writeFileSync(p, JSON.stringify(settings, null, 2) + '\n');
  return p;
}

/** Keep generated reports out of version control while allowing config.json to be committed. */
export function ensureOutputIgnore(dir: string): void {
  const gi = path.join(dir, '.gitignore');
  if (!existsSync(gi)) writeFileSync(gi, '# Generated by flowlens. config.json may be committed.\n*\n!config.json\n!.gitignore\n');
}
